import fs from 'node:fs/promises'
import path from 'node:path'
import crypto from 'node:crypto'
import { parseMME } from '../src/utils/scaUtils.js'

const root = process.argv[2] || 'test-projects/recovery-mme'
const outPath = process.argv[3] || path.join(root, 'recovery-mme-audit.md')

const mediaFields = ['file', 'mediaSourcePath', 'mediaFile', 'btnImage', 'hoverSoundFile', 'clickSoundFile']

function hash(text) {
  return crypto.createHash('sha256').update(text).digest('hex').slice(0, 12)
}

function normalizeForHash(text) {
  return text
    .replace(/^\/\/ \d{4}-\d{2}-\d{2}T.*$/gm, '// <timestamp>')
    .replace(/\r\n/g, '\n')
}

function countBy(items, fn) {
  const out = {}
  for (const item of items) {
    const key = fn(item) || 'unknown'
    out[key] = (out[key] || 0) + 1
  }
  return out
}

function pathExistsMaybe(value) {
  if (!value || typeof value !== 'string') return null
  if (/^(data:|blob:|https?:|app-media:|file:)/i.test(value)) return null
  if (!/^[a-zA-Z]:[\\/]/.test(value) && !value.startsWith('\\\\')) return null
  return value
}

function collectMedia(parsed) {
  const rows = []
  for (const [pageIdx, page] of parsed.pages.entries()) {
    const pageName = page.name || `Page ${pageIdx + 1}`
    for (const key of ['bgMediaSourcePath', 'bgMediaSrc', 'bgImage', 'bgSourcePath']) {
      const value = pathExistsMaybe(page[key])
      if (value) rows.push({ page: pageName, element: '(page)', field: key, value })
    }
    if (page.sound) {
      for (const key of ['file', 'sourcePath']) {
        const value = pathExistsMaybe(page.sound[key])
        if (value) rows.push({ page: pageName, element: '(sound)', field: `sound.${key}`, value })
      }
    }
    if (page.narration) {
      for (const key of ['file', 'sourcePath']) {
        const value = pathExistsMaybe(page.narration[key])
        if (value) rows.push({ page: pageName, element: '(narration)', field: `narration.${key}`, value })
      }
    }
    for (const [elIdx, el] of (page.elements || []).entries()) {
      const elName = el.elLabel || el.mediaName || el.label || el.content || `${el.type || 'element'} ${elIdx + 1}`
      for (const key of mediaFields) {
        const value = pathExistsMaybe(el[key])
        if (value) rows.push({ page: pageName, element: String(elName).slice(0, 60), field: key, value })
      }
    }
  }
  return rows
}

function collectActions(parsed) {
  const rows = []
  for (const [pageIdx, page] of parsed.pages.entries()) {
    const pageName = page.name || `Page ${pageIdx + 1}`
    for (const [elIdx, el] of (page.elements || []).entries()) {
      if (el.action || el.linkTarget || el.target || el.afterPlay || el.actionChain?.length) {
        rows.push({
          page: pageName,
          element: el.elLabel || el.label || el.content || `${el.type || 'element'} ${elIdx + 1}`,
          type: el.type || '',
          action: el.action || '',
          target: el.target || el.linkTarget || '',
          afterPlay: el.afterPlay || '',
          actionChain: Array.isArray(el.actionChain) ? el.actionChain.length : 0,
        })
      }
    }
  }
  return rows
}

function unique(arr) {
  return [...new Set(arr)]
}

async function main() {
  const entries = await fs.readdir(root, { withFileTypes: true })
  const mmeFiles = entries
    .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith('.mme'))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b))

  const reports = []
  for (const name of mmeFiles) {
    const filePath = path.join(root, name)
    const text = await fs.readFile(filePath, 'utf8')
    let parsed
    let parseError = ''
    try {
      parsed = parseMME(text)
    } catch (err) {
      parseError = err?.stack || err?.message || String(err)
      parsed = { pages: [], stage: null, presentationAudio: null, projectVars: null, warnings: [] }
    }
    const elements = parsed.pages.flatMap((page) => page.elements || [])
    const media = collectMedia(parsed)
    const checkedMedia = await Promise.all(media.map(async (row) => {
      let exists = false
      try {
        await fs.access(row.value)
        exists = true
      } catch {
        exists = false
      }
      return { ...row, exists }
    }))
    const missingMedia = checkedMedia.filter((row) => !row.exists)
    const actions = collectActions(parsed)
    reports.push({
      name,
      size: Buffer.byteLength(text),
      hash: hash(text),
      normalizedHash: hash(normalizeForHash(text)),
      generatedBy: text.match(/^\/\/ Generated by (.+)$/m)?.[1] || '',
      stageComment: text.match(/^\/\/ Stage (.+)$/m)?.[1] || '',
      timestamp: text.match(/^\/\/ (\d{4}-\d{2}-\d{2}T.+)$/m)?.[1] || '',
      parseError,
      warningCount: parsed.warnings?.length || 0,
      warnings: parsed.warnings || [],
      pages: parsed.pages.length,
      stage: parsed.stage,
      hasPresentationAudio: !!parsed.presentationAudio,
      projectVars: parsed.projectVars?.length || 0,
      elements: elements.length,
      elementTypes: countBy(elements, (el) => el.type),
      pageModes: countBy(parsed.pages, (page) => page.timing?.mode),
      lyricPages: parsed.pages.filter((page) => page.lyricStart != null || page.lyricEnd != null || page.timing?.mode === 'lyric').length,
      wordTimestampPages: parsed.pages.filter((page) => page.wordTimestamps?.length).length,
      mediaRefs: checkedMedia.length,
      missingMedia,
      actions,
      pageNames: parsed.pages.map((page) => page.name || ''),
    })
  }

  const lines = []
  lines.push('# Recovery MME Audit')
  lines.push('')
  lines.push(`Generated: ${new Date().toISOString()}`)
  lines.push(`Folder: \`${root}\``)
  lines.push('')
  lines.push('## Summary')
  lines.push('')
  lines.push('| File | Pages | Elements | Stage | Audio | Media refs | Missing media | Warnings | Hash |')
  lines.push('| --- | ---: | ---: | --- | --- | ---: | ---: | ---: | --- |')
  for (const r of reports) {
    lines.push(`| ${r.name} | ${r.pages} | ${r.elements} | ${r.stage?.width || '?'}x${r.stage?.height || '?'} | ${r.hasPresentationAudio ? 'yes' : 'no'} | ${r.mediaRefs} | ${r.missingMedia.length} | ${r.warningCount}${r.parseError ? ' + parse error' : ''} | ${r.normalizedHash} |`)
  }

  lines.push('')
  lines.push('## File Details')
  for (const r of reports) {
    lines.push('')
    lines.push(`### ${r.name}`)
    lines.push('')
    lines.push(`- Generated by: ${r.generatedBy || '(unknown)'}`)
    lines.push(`- Timestamp: ${r.timestamp || '(unknown)'}`)
    lines.push(`- Stage comment: ${r.stageComment || '(none)'}`)
    lines.push(`- Parsed stage: ${r.stage?.width || '?'}x${r.stage?.height || '?'}`)
    lines.push(`- Pages: ${r.pages}`)
    lines.push(`- Elements: ${r.elements}`)
    lines.push(`- Element types: \`${JSON.stringify(r.elementTypes)}\``)
    lines.push(`- Page modes: \`${JSON.stringify(r.pageModes)}\``)
    lines.push(`- Lyric/timed pages: ${r.lyricPages}`)
    lines.push(`- Pages with word timestamps: ${r.wordTimestampPages}`)
    lines.push(`- Presentation audio: ${r.hasPresentationAudio ? 'yes' : 'no'}`)
    lines.push(`- Project vars: ${r.projectVars}`)
    if (r.parseError) {
      lines.push('')
      lines.push('Parse error:')
      lines.push('```')
      lines.push(r.parseError)
      lines.push('```')
    }
    if (r.warnings.length) {
      lines.push('')
      lines.push('Warnings:')
      for (const warning of r.warnings) lines.push(`- ${warning}`)
    }
    if (r.missingMedia.length) {
      lines.push('')
      lines.push('Missing media/native path references:')
      for (const row of r.missingMedia.slice(0, 40)) {
        lines.push(`- ${row.page} / ${row.element} / ${row.field}: \`${row.value}\``)
      }
      if (r.missingMedia.length > 40) lines.push(`- ... ${r.missingMedia.length - 40} more`)
    }
    if (r.actions.length) {
      lines.push('')
      lines.push('Actions/interactions:')
      for (const action of r.actions.slice(0, 30)) {
        lines.push(`- ${action.page} / ${action.element}: type=${action.type}, action=${action.action}, target=${action.target}, afterPlay=${action.afterPlay}, chain=${action.actionChain}`)
      }
      if (r.actions.length > 30) lines.push(`- ... ${r.actions.length - 30} more`)
    }
  }

  const before = reports.find((r) => r.name === '01-before-crash-working.mme')
  const after = reports.find((r) => r.name === '02-after-crash-broken.mme')
  if (before && after) {
    lines.push('')
    lines.push('## Before vs After Crash Pair')
    lines.push('')
    lines.push(`- Normalized hash equal: ${before.normalizedHash === after.normalizedHash ? 'yes' : 'no'}`)
    lines.push(`- Page count delta: ${after.pages - before.pages}`)
    lines.push(`- Element count delta: ${after.elements - before.elements}`)
    lines.push(`- Missing media delta: ${after.missingMedia.length - before.missingMedia.length}`)
    const beforeNames = before.pageNames.join('\n')
    const afterNames = after.pageNames.join('\n')
    lines.push(`- Page names equal: ${beforeNames === afterNames ? 'yes' : 'no'}`)
    const uniqueBeforeMissing = unique(before.missingMedia.map((row) => row.value))
    const uniqueAfterMissing = unique(after.missingMedia.map((row) => row.value))
    lines.push(`- Unique missing media before: ${uniqueBeforeMissing.length}`)
    lines.push(`- Unique missing media after: ${uniqueAfterMissing.length}`)
  }

  await fs.writeFile(outPath, lines.join('\n'), 'utf8')
  console.log(`Wrote ${outPath}`)
}

main().catch((err) => {
  console.error(err)
  process.exitCode = 1
})
